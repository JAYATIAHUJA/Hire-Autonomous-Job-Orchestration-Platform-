"""Start the Hire dev stack with one command.

    python scripts/dev.py               # db, redis, s3, api, worker, web, mock-ats
    python scripts/dev.py --computers   # also build and start the OpenBot supervisor + computer image
    python scripts/dev.py --down        # stop the stack (keeps volumes)

On first run it writes .env next to compose.yml with fresh random secrets. Existing values
in .env are never overwritten.
"""

import argparse
import secrets
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env"

GENERATED = {
    "CONSENT_SIGNING_SECRET": lambda: secrets.token_hex(32),
    "S3_ACCESS_KEY": lambda: "hire",
    "S3_SECRET_KEY": lambda: secrets.token_hex(24),
    "COMPUTER_SUPERVISOR_TOKEN": lambda: secrets.token_hex(32),
    "COMPUTER_TOKEN": lambda: secrets.token_hex(32),
    "LIVE_FEEDS_ENABLED": lambda: "false",
}


def ensure_env() -> None:
    existing: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, value = line.split("=", 1)
                existing[key.strip()] = value.strip()

    missing = {k: make() for k, make in GENERATED.items() if not existing.get(k)}
    if not missing:
        return
    with ENV_FILE.open("a", encoding="utf-8") as fh:
        if not existing:
            fh.write("# Local dev secrets for compose.yml. Generated by scripts/dev.py. Never commit.\n")
        for key, value in missing.items():
            fh.write(f"{key}={value}\n")
    print(f"wrote {len(missing)} value(s) to {ENV_FILE}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--computers", action="store_true", help="also start the browser computers")
    parser.add_argument("--down", action="store_true", help="stop the stack")
    parser.add_argument("--detach", "-d", action="store_true", help="run in the background")
    args = parser.parse_args()

    ensure_env()
    cmd = ["docker", "compose", "--project-directory", str(ROOT)]
    if args.computers:
        cmd += ["--profile", "computers"]
    if args.down:
        cmd += ["down"]
    else:
        cmd += ["up", "--build"] + (["--detach"] if args.detach else [])
    print("$", " ".join(cmd))
    return subprocess.call(cmd, cwd=ROOT)


if __name__ == "__main__":
    sys.exit(main())
