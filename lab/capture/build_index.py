"""Regenerate lab/fixtures/INDEX.md from every fixture's meta.json. Offline; no network.

    python lab/capture/build_index.py
"""

import json
from pathlib import Path

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures"

STRESS_LABELS = {
    "cover_letter_upload": "cover letter upload",
    "multi_file_upload": "multiple file inputs",
    "how_did_you_hear": "how did you hear",
    "work_authorisation": "work authorisation / sponsorship",
    "eeo_demographics": "EEO / demographic block",
    "location": "location (often autocomplete)",
    "notice_period": "notice period",
    "salary_ctc": "salary / CTC",
    "linkedin_url": "LinkedIn URL",
    "github_or_portfolio": "GitHub / portfolio",
    "consent_privacy": "consent / privacy checkbox",
    "dropdowns": "dropdowns / comboboxes",
    "radio_or_checkbox": "radios / checkboxes",
    "free_text": "free-text answers",
    "custom_questions": "custom questions",
}


def size_of(path: Path) -> int:
    return sum(f.stat().st_size for f in path.rglob("*") if f.is_file())


def main() -> None:
    rows = []
    for meta_path in sorted(FIXTURES.glob("*/*/meta.json")):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        rows.append((meta_path.parent, meta))
    total = sum(size_of(d) for d, _ in rows)
    counts: dict[str, int] = {}
    for _, m in rows:
        counts[m["ats"]] = counts.get(m["ats"], 0) + 1

    lines = [
        "# Form lab fixtures",
        "",
        "Saved copies of real, public job application forms, served offline by the mock ATS at",
        "`/fixtures/<ats>/<id>/`. Every form posts to the mock's `/submit`; nothing reaches the employer.",
        "Generated by `python lab/capture/build_index.py`; recapture with `python lab/capture/capture.py lab/capture/targets.json`.",
        "",
        f"{len(rows)} fixtures ({', '.join(f'{v} {k}' for k, v in sorted(counts.items()))}), "
        f"{total / 1024 / 1024:.1f} MB in total. Field counts are the visible controls in the captured DOM",
        "(hidden inputs excluded); \"req\" is how many are marked required.",
        "",
        "| # | Fixture | Variant | Role | Location | Fields (req) | Files | What it stresses |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i, (d, m) in enumerate(rows, 1):
        key = f"{m['ats']}/{d.name}"
        stresses = ", ".join(STRESS_LABELS.get(n, n) for n in m.get("notable_fields", []))
        title = (m.get("title") or "").replace("|", "/")
        location = (m.get("location") or "").replace("|", "/")
        lines.append(
            f"| {i} | `{key}` | {m.get('variant', '')} | {title} | {location} | "
            f"{m['field_count']} ({m.get('required_count', 0)}) | {m.get('file_inputs', 0)} | {stresses} |"
        )
    lines += [
        "",
        "## What was changed from the live page",
        "",
        "- The DOM is the *rendered* page (Lever and Ashby build their forms client-side), captured with headless Chromium.",
        "- All `<script>`, `<iframe>`, `<noscript>`, inline event handlers, preload hints and tracking pixels are removed.",
        "  Without scripts, client-side widgets (React comboboxes, location autocomplete, drag-and-drop upload) are frozen",
        "  in their initial state: the controls are there, the behaviour is not.",
        "- Every `<form>` posts `multipart/form-data` to `/submit` with a hidden `_lab_fixture` field; the original action is",
        "  kept in `data-lab-orig-action`. Ashby renders no `<form>` element, so its controls are wrapped in one",
        "  (`data-lab-wrapped`). Controls without a `name` get their `id` as name (`data-lab-named`).",
        "- Links point at `#` (original in `data-lab-href`). Images are a 1x1 placeholder; fonts and media are not saved.",
        "- Stylesheets are saved under `assets/`, pruned to the rules that match the saved DOM.",
        "- The two embedded fixtures are the real Greenhouse embed (`frame.html`) inside a minimal stand-in careers page",
        "  (`page.html`); the employer's own careers site is not captured.",
        "- `questions.json` (Greenhouse only) is the public `?questions=true` board API response without the job description.",
        "",
    ]
    (FIXTURES / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {FIXTURES / 'INDEX.md'}: {len(rows)} fixtures, {total} bytes")


if __name__ == "__main__":
    main()
